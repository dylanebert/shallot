import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { $ } from "bun";
import { rustSourceRemaps } from "../../../scripts/rust-remap";
import { optimize, version } from "../../../scripts/wasm-opt";
import { MIKKTSPACE_ARTIFACT, mikktspaceInputHash } from "./inputs";

const root = resolve(import.meta.dir, "../../..");
const flags = ["-C target-feature=+simd128", "--remap-path-prefix=crates/mikktspace/=", ...rustSourceRemaps()].join(" ");
await $`cargo build --locked -p shallot-mikktspace --target wasm32-unknown-unknown --release`.cwd(root).env({ ...process.env, RUSTFLAGS: flags });
const raw = resolve(root, "target/wasm32-unknown-unknown/release/shallot_mikktspace.wasm");
const output = resolve(root, "target/shallot_mikktspace.opt.wasm");
await optimize(raw, output);
const bytes = readFileSync(output);
writeFileSync(resolve(root, MIKKTSPACE_ARTIFACT), `// Generated by bun crates/mikktspace/scripts/build.ts; do not edit.
// Build inputs: sha256:${mikktspaceInputHash(root)}
// ${await version()}; ${bytes.length} bytes. MikkTSpace license: crates/mikktspace/licenses/.
export const MIKKTSPACE_WASM_BASE64 =
    "${bytes.toString("base64")}";
`);
