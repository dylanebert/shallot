import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { $ } from "bun";
import { rustSourceRemaps } from "../../../scripts/rust-remap";
import { WASM_MEMORY_FLAG } from "../../../scripts/wasm-memory";
import { optimize, version } from "../../../scripts/wasm-opt";
import { DRACO_ARTIFACT, dracoInputHash } from "./inputs";

const root = resolve(import.meta.dir, "../../..");
const flags = [WASM_MEMORY_FLAG, "--remap-path-prefix=crates/draco/=", ...rustSourceRemaps()].join(" ");
await $`cargo build --locked -p shallot-draco --target wasm32-unknown-unknown --release`.cwd(root).env({ ...process.env, RUSTFLAGS: flags });
const raw = resolve(root, "target/wasm32-unknown-unknown/release/shallot_draco.wasm");
const output = resolve(root, "target/shallot_draco.opt.wasm");
await optimize(raw, output);
const bytes = readFileSync(output);
writeFileSync(resolve(root, DRACO_ARTIFACT), `// Generated by bun crates/draco/scripts/build.ts; do not edit.
// Build inputs: sha256:${dracoInputHash(root)}
// ${await version()}; ${bytes.length} bytes.
export const DRACO_WASM_BASE64 =
    "${bytes.toString("base64")}";
`);
