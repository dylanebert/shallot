import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { $ } from "bun";
import { rustSourceRemaps } from "../../../scripts/rust-remap";
import { WASM_MEMORY_FLAG } from "../../../scripts/wasm-memory";
import { optimize, version } from "../../../scripts/wasm-opt";
import { GLTF_ARTIFACT, gltfInputHash } from "./inputs";

const root = resolve(import.meta.dir, "../../..");
const flags = [WASM_MEMORY_FLAG, "-C target-feature=+simd128", "--remap-path-prefix=crates/gltf/=", ...rustSourceRemaps()].join(" ");
await $`cargo build --locked -p shallot-gltf --target wasm32-unknown-unknown --release`.cwd(root).env({ ...process.env, RUSTFLAGS: flags });
const raw = resolve(root, "target/wasm32-unknown-unknown/release/shallot_gltf.wasm");
const output = resolve(root, "target/shallot_gltf.opt.wasm");
await optimize(raw, output);
const bytes = readFileSync(output);
writeFileSync(resolve(root, GLTF_ARTIFACT), `// Generated by bun crates/gltf/scripts/build.ts; do not edit.
// Build inputs: sha256:${gltfInputHash(root)}
// ${await version()}; ${bytes.length} bytes.
export const GLTF_WASM_BASE64 =
    "${bytes.toString("base64")}";
`);
